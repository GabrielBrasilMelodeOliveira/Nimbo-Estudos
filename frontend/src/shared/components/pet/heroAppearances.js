// Names also describe standalone previews. XP thresholds are owned by the server.
export const heroClassNames = [
  "Pessoa Comum",
  "Aprendiz",
  "Soldado",
  "Guardião da Vigília",
  "Mestre de Batalha",
  "Comandante da Aurora",
  "Lenda da Constância",
];
export function heroRank(stage) {
  return Math.min(
    heroClassNames.length,
    Math.max(1, Math.trunc(Number(stage) || 1)),
  );
}
export const heroClassName = (stage) => heroClassNames[heroRank(stage) - 1];
