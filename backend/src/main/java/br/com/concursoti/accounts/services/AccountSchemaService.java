package br.com.concursoti.accounts.services;

import java.util.*;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;

/** One PostgreSQL schema per account isolates IDs, foreign keys, blobs, aggregates and bulk deletes. */
@Service
public class AccountSchemaService {

  public static final List<String> TABLES = List.of(
    "agenda_items",
    "asset_blobs",
    "daily_goal_days",
    "daily_goal_settings",
    "daily_study_plans",
    "disciplines",
    "edital_imports",
    "error_notes",
    "manual_flashcards",
    "materials",
    "mock_exams",
    "period_goals",
    "pet_companions",
    "question_records",
    "review_tasks",
    "stored_assets",
    "study_plan",
    "study_pet",
    "study_sessions",
    "topics"
  );
  private final JdbcTemplate jdbc;

  public AccountSchemaService(@Qualifier("accountJdbc") JdbcTemplate jdbc) {
    this.jdbc = jdbc;
  }

  public void synchronize(String schema) {
    if (!schema.matches("nimbo_[a-f0-9]{32}")) {
      throw new IllegalArgumentException("Área inválida.");
    }
    jdbc.execute("create schema if not exists " + quote(schema));
    for (String tableName : TABLES) {
      jdbc.execute(
        "create table if not exists " +
          table(schema, tableName) +
          " (like public." +
          quote(tableName) +
          " including all)"
      );
      addMissingColumns(schema, tableName);
    }
    // LIKE omits foreign keys. Rebuild them only after all target tables exist.
    for (String tableName : TABLES) {
      addMissingForeignKeys(schema, tableName);
    }
  }

  private void addMissingColumns(String schema, String tableName) {
    var columns = jdbc.queryForList(
      """
      select attribute.attname as name,
             format_type(attribute.atttypid, attribute.atttypmod) as type,
             attribute.attnotnull as required, attribute.attidentity as identity,
             pg_get_expr(default_value.adbin, default_value.adrelid) as expression
      from pg_attribute attribute
      join pg_class source on source.oid = attribute.attrelid
      join pg_namespace namespace on namespace.oid = source.relnamespace
      left join pg_attrdef default_value
        on default_value.adrelid = attribute.attrelid
       and default_value.adnum = attribute.attnum
      where namespace.nspname = 'public' and source.relname = ?
        and attribute.attnum > 0 and not attribute.attisdropped
      """,
      tableName
    );
    var presentColumns = new HashSet<>(
      jdbc.queryForList(
        """
        select column_name from information_schema.columns
        where table_schema = ? and table_name = ?
        """,
        String.class,
        schema,
        tableName
      )
    );
    for (var column : columns) {
      String columnName = column.get("name").toString();
      if (presentColumns.contains(columnName)) {
        continue;
      }
      String definition = column.get("type").toString();
      if (!column.get("identity").toString().isEmpty()) {
        definition += " generated by default as identity";
      } else if (column.get("expression") != null) {
        definition += " default " + column.get("expression");
      }
      if (Boolean.TRUE.equals(column.get("required"))) {
        definition += " not null";
      }
      jdbc.execute(
        "alter table " +
          table(schema, tableName) +
          " add column " +
          quote(columnName) +
          " " +
          definition
      );
    }
  }

  private void addMissingForeignKeys(String schema, String tableName) {
    var constraints = jdbc.queryForList(
      """
      select constraint_definition.conname as name,
             pg_get_constraintdef(constraint_definition.oid) as definition,
             target.relname as target
      from pg_constraint constraint_definition
      join pg_class source on source.oid = constraint_definition.conrelid
      join pg_namespace namespace on namespace.oid = source.relnamespace
      join pg_class target on target.oid = constraint_definition.confrelid
      where namespace.nspname = 'public' and source.relname = ?
        and constraint_definition.contype = 'f'
      """,
      tableName
    );
    for (var constraint : constraints) {
      String target = constraint.get("target").toString();
      if (!TABLES.contains(target)) {
        throw new IllegalStateException("Referência fora da área de estudos.");
      }
      String constraintName = constraint.get("name").toString();
      if (foreignKeyExists(schema, tableName, constraintName)) {
        continue;
      }
      String definition = constraint
        .get("definition")
        .toString()
        .replaceFirst(
          "REFERENCES (?:public\\.)?\"?" + target + "\"?",
          "REFERENCES " + table(schema, target)
        );
      jdbc.execute(
        "alter table " +
          table(schema, tableName) +
          " add constraint " +
          quote(constraintName) +
          " " +
          definition
      );
    }
  }

  private boolean foreignKeyExists(
    String schema,
    String tableName,
    String constraintName
  ) {
    return Boolean.TRUE.equals(
      jdbc.queryForObject(
        """
        select exists (
          select 1 from pg_constraint constraint_definition
          join pg_class source on source.oid = constraint_definition.conrelid
          join pg_namespace namespace on namespace.oid = source.relnamespace
          where namespace.nspname = ? and source.relname = ?
            and constraint_definition.conname = ?
        )
        """,
        Boolean.class,
        schema,
        tableName,
        constraintName
      )
    );
  }

  private static String table(String schema, String name) {
    return quote(schema) + "." + quote(name);
  }

  private static String quote(String identifier) {
    return "\"" + identifier.replace("\"", "\"\"") + "\"";
  }
}
